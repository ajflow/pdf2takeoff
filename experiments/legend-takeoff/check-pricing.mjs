import assert from 'node:assert/strict';
import { moneyCents, priceQuantities } from './pricing.mjs';
assert.equal(moneyCents('0.10'),10);
assert.equal(moneyCents('0'),0);
for(const s of ['', '-2','NaN','Infinity','1.001','1e3','1000001'])assert.equal(moneyCents(s),null);
const quantities=[{code:'DL1',status:'assessed',supported:3,unresolved:0},{code:'SO1',status:'assessed',supported:2,unresolved:0}];
const rates={DL1:{material:'40',labour:'20'},SO1:{material:'25',labour:'15'}};
assert.deepEqual(priceQuantities(quantities,rates).lines.map(l=>l.totalCents),[18000,8000]);
assert.equal(priceQuantities(quantities,rates).pricedSubtotalCents,26000);
assert.equal(priceQuantities(quantities,rates).complete,true);
const flagged=priceQuantities([{...quantities[0],supported:2,unresolved:1}],rates);
assert.equal(flagged.pricedSubtotalCents,12000);
assert.equal(flagged.complete,false);
const missing=priceQuantities([{code:'DL1',status:'not-assessed',supported:null,unresolved:null}],rates);
assert.equal(missing.lines[0].totalCents,null);
assert.equal(missing.complete,false);
assert.equal(priceQuantities(quantities,{}).lines[0].status,'rate-required');
assert.equal(priceQuantities([{...quantities[0],supported:0}],{DL1:{material:'0',labour:'0'}}).lines[0].totalCents,0);
console.log('PASS: pricing arithmetic, cents, missing rates, unknown quantities and unresolved exclusions');
